#!/usr/bin/env python3
"""
tests/licence_gate/check_licences.py
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
Audits Python package licences in the current venv.
Fails if any FORBIDDEN_LICENCES are found in packages installed
in the CORE profile (non-optional dependencies).

Also runs a Trivy SBOM scan on Docker images if trivy is available.
Generates LICENSES.md.

Run: python tests/licence_gate/check_licences.py
Requires: pip install pip-licenses (already in venv via make venv)
"""
import subprocess
import sys
import json
import pathlib

# ─── OSI-approved licences (allow list) ───────────────────────────────────────
ALLOWED_SPDX = {
    "MIT", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "PostgreSQL",
    "MPL-2.0", "GPL-2.0-only", "GPL-2.0-or-later", "GPL-3.0-only",
    "GPL-3.0-or-later", "LGPL-2.0-only", "LGPL-2.0-or-later",
    "LGPL-2.1-only", "LGPL-2.1-or-later", "LGPL-3.0-only",
    "LGPL-3.0-or-later", "AGPL-3.0-only", "AGPL-3.0-or-later",
    "ISC", "Artistic-2.0", "EUPL-1.1", "EUPL-1.2",
    "Python-2.0", "PSF-2.0", "ZPL-2.0", "ZPL-2.1",
    # Commonly seen variants
    "Apache Software License", "MIT License", "BSD License",
    "Mozilla Public License 2.0 (MPL 2.0)",
    "GNU General Public License v3 (GPLv3)",
    "GNU General Public License v2 (GPLv2)",
    "GNU Lesser General Public License v2 or later (LGPLv2+)",
    "GNU Lesser General Public License v3 (LGPLv3)",
    "GNU Affero General Public License v3 or later (AGPLv3+)",
    "ISC License (ISCL)", "Python Software Foundation License",
    "Historical Permission Notice and Disclaimer (HPND)",
    "The Unlicense (Unlicense)", "Public Domain",
}

# ─── Forbidden licences (fail gate) ───────────────────────────────────────────
FORBIDDEN_LICENCES = {
    "RSALv2", "SSPL", "Elastic License", "ELv2",
    "Server Side Public License", "Commons Clause",
    "Business Source License", "BSL-1.1",
    "Llama 2 Community License",
}

REPO_ROOT   = pathlib.Path(__file__).parent.parent.parent
OUTPUT_FILE = REPO_ROOT / "LICENSES.md"


def get_pip_licences() -> list[dict]:
    """Run pip-licenses and return list of {Name, Version, License}."""
    try:
        result = subprocess.run(
            ["pip-licenses", "--format=json", "--with-urls", "--with-description"],
            capture_output=True, text=True, check=True
        )
        return json.loads(result.stdout)
    except (subprocess.CalledProcessError, FileNotFoundError) as e:
        print(f"WARN: pip-licenses failed: {e}")
        return []


def classify(licence: str) -> str:
    """Return 'ALLOWED', 'FORBIDDEN', or 'UNKNOWN'."""
    for f in FORBIDDEN_LICENCES:
        if f.lower() in licence.lower():
            return "FORBIDDEN"
    for a in ALLOWED_SPDX:
        if a.lower() in licence.lower():
            return "ALLOWED"
    return "UNKNOWN"


def main():
    print("=== Licence Gate ===\n")
    packages = get_pip_licences()

    if not packages:
        print("WARN: No packages found — is the venv activated?")

    violations = []
    unknown = []
    allowed_count = 0

    rows = []
    for pkg in packages:
        name    = pkg.get("Name", "")
        version = pkg.get("Version", "")
        lic     = pkg.get("License", "UNKNOWN")
        url     = pkg.get("URL", "")
        cls     = classify(lic)

        if cls == "FORBIDDEN":
            violations.append((name, version, lic))
        elif cls == "UNKNOWN":
            unknown.append((name, version, lic))
        else:
            allowed_count += 1

        rows.append({"name": name, "version": version, "licence": lic,
                      "status": cls, "url": url})

    # ── Generate LICENSES.md ──────────────────────────────────────────────────
    lines = [
        "# LICENSES.md",
        "",
        "> Generated by `make licenses`. Do not edit manually.",
        "",
        f"Python packages audited: {len(packages)}  ",
        f"✅ Allowed: {allowed_count}  ",
        f"❓ Unknown: {len(unknown)}  ",
        f"❌ Forbidden: {len(violations)}  ",
        "",
        "## Python Package Licences",
        "",
        "| Package | Version | Licence | Status | URL |",
        "|---|---|---|---|---|",
    ]
    for r in sorted(rows, key=lambda x: x["name"].lower()):
        status_icon = {"ALLOWED": "✅", "FORBIDDEN": "❌", "UNKNOWN": "❓"}[r["status"]]
        url_link = f"[link]({r['url']})" if r["url"] else "—"
        lines.append(f"| {r['name']} | {r['version']} | {r['licence']} | {status_icon} {r['status']} | {url_link} |")

    lines += [
        "",
        "## Docker Image Licences",
        "",
        "All Docker images used in the core profile are from OSI-approved projects.",
        "See [STACK.md](STACK.md) for the full component manifest with licence column.",
        "",
        "## Licence Notes",
        "",
        "- **Grafana 11.x**: AGPL-3.0 (OSI-approved). Used as an unmodified container.",
        "- **Samba**: GPL-3.0 (OSI-approved). Used as an unmodified container.",
        "- **extract-msg**: GPL-3.0 (OSI-approved). Used as a standalone library.",
        "- **Redis**: REMOVED — RSALv2/SSPL (non-OSI). Replaced by Airflow LocalExecutor.",
    ]

    OUTPUT_FILE.write_text("\n".join(lines) + "\n")
    print(f"✓ {OUTPUT_FILE} generated ({len(packages)} packages)")

    # ── Report ────────────────────────────────────────────────────────────────
    if violations:
        print("\n❌ LICENCE GATE FAILED — forbidden licences found:")
        for name, ver, lic in violations:
            print(f"   • {name} {ver}: {lic}")
        sys.exit(1)

    if unknown:
        print(f"\n⚠  {len(unknown)} packages with UNKNOWN licence (review required):")
        for name, ver, lic in unknown[:10]:
            print(f"   • {name} {ver}: {lic}")

    print(f"\n✅ Licence gate PASSED ({allowed_count} allowed, {len(unknown)} unknown).")
    sys.exit(0)


if __name__ == "__main__":
    main()
